"""Finite projected searches, with every transition supplied by coach.cube."""

from dataclasses import dataclass
from functools import lru_cache
from heapq import heappop, heappush

import numpy as np

from coach.cube import CubeState, inverse_sequence, piece_coordinate_maps

SLOTS = ("FR", "FL", "BL", "BR")
TURNS = tuple(face + suffix for face in "URFDLB" for suffix in ("", "2", "'"))


def cross_code(state: CubeState) -> int:
    return sum(state.piece_coordinate("edge", piece) * 24**i for i, piece in enumerate(range(4, 8)))


@lru_cache(maxsize=1)
def cross_table():
    """Complete reverse BFS: 190,080 legal four-edge coordinates, diameter 8 HTM."""
    codes = np.arange(24**4, dtype=np.uint32)
    maps = np.array([piece_coordinate_maps(move)[1] for move in TURNS], dtype=np.uint32)
    transitions = np.zeros((len(codes), len(TURNS)), dtype=np.uint32)
    for i in range(4):
        transitions += maps[:, (codes // 24**i) % 24].T * 24**i
    distance = np.full(len(codes), 255, dtype=np.uint8)
    root = cross_code(CubeState())
    distance[root] = 0
    frontier, depth = np.array([root], dtype=np.uint32), 0
    while len(frontier):
        neighbors = transitions[frontier].reshape(-1)
        frontier = np.unique(neighbors[distance[neighbors] == 255])
        depth += 1
        distance[frontier] = depth
    if np.count_nonzero(distance != 255) != 190080 or distance[distance != 255].max() != 8:
        raise ValueError("Cross table coverage failed")
    return transitions, distance


def solve_cross(state: CubeState) -> str:
    transitions, distance = cross_table()
    code, words = cross_code(state), []
    while distance[code]:
        candidates = []
        for i, move in enumerate(TURNS):
            if distance[transitions[code, i]] + 1 == distance[code]:
                after = state.apply(move)
                pairs = sum(after.layer_progress()["pairs"].values())
                candidates.append((-pairs, i, after))
        if not candidates:
            raise ValueError("Cross coordinate is unreachable")
        _, i, state = min(candidates, key=lambda row: row[:2])
        words.append(TURNS[i])
        code = int(transitions[code, i])
    return " ".join(words)


@dataclass(frozen=True)
class Macro:
    id: str
    notation: str
    cost: int
    preserved: int
    corners: tuple[int, ...]
    edges: tuple[int, ...]

    def apply_pair(self, code: int) -> int:
        return self.corners[code // 24] * 24 + self.edges[code % 24]


@lru_cache(maxsize=1)
def macros() -> tuple[Macro, ...]:
    words = [(f"U-{q or '1'}", "U" + q) for q in ("", "2", "'")]
    for face in "RFLB":
        for side in (face, face + "'"):
            for q in ("", "2", "'"):
                word = f"{side} U{q} {inverse_sequence(side)}"
                words.append((f"trigger-{side}-U{q}", word))
    result = []
    for name, word in words:
        progress = CubeState().apply(word).layer_progress()
        if not progress["cross"]:
            raise ValueError("F2L macro disturbed cross")
        preserved = sum(1 << i for i, slot in enumerate(SLOTS) if progress["pairs"][slot])
        corners, edges = piece_coordinate_maps(word)
        result.append(Macro(name, word, len(word.split()), preserved, corners, edges))
    return tuple(result)


def pair_code(state: CubeState, slot: int) -> int:
    return state.piece_coordinate("corner", slot + 4) * 24 + state.piece_coordinate(
        "edge", slot + 8
    )


@lru_cache(maxsize=32)
def pair_table(slot: int, protected: int):
    """Dijkstra on the exact target pair, using only progress-preserving macros.

    The group generated by U and slot triggers reaches every legal target-pair
    coordinate outside the protected slots (384/294/216/150 configurations).
    This is shortest in this macro graph, not a claim of human or HTM optimal F2L.
    """
    if protected & (1 << slot):
        raise ValueError("Target slot must be unprotected")
    allowed = tuple(macro for macro in macros() if macro.preserved & protected == protected)
    root = pair_code(CubeState(), slot)
    distance = [10000] * 576
    distance[root] = 0
    queue = [(0, root)]
    while queue:
        cost, code = heappop(queue)
        if distance[code] != cost:
            continue
        for macro in allowed:
            after = macro.apply_pair(code)
            new = cost + macro.cost
            if new < distance[after]:
                distance[after] = new
                heappush(queue, (new, after))
    expected = 6 * (8 - protected.bit_count()) ** 2
    if sum(d < 10000 for d in distance) != expected:
        raise ValueError("F2L projected case coverage failed")
    return allowed, tuple(distance)


def solve_pair(state: CubeState, slot: int, protected: int) -> tuple[str, list[str]]:
    allowed, distance = pair_table(slot, protected)
    code, selected, ids = pair_code(state, slot), [], []
    if distance[code] == 10000:
        raise ValueError("Pair occupies a protected slot or the cross is not solved")
    while distance[code]:
        macro = next(
            (m for m in allowed if distance[m.apply_pair(code)] + m.cost == distance[code]), None
        )
        if macro is None:
            raise ValueError("F2L table has no descending transition")
        selected.append(macro.notation)
        ids.append(macro.id)
        state = state.apply(macro.notation)
        progress = state.layer_progress()
        if not progress["cross"] or any(
            not progress["pairs"][SLOTS[i]] for i in range(4) if protected & (1 << i)
        ):
            raise ValueError("A pair macro failed protected-progress verification")
        code = pair_code(state, slot)
    return " ".join(selected), ids
